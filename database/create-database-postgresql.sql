CREATE TABLE public.Comments (
    CommentId        INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    PostId           INT               NOT NULL,
    UserId           INT               NOT NULL,
    ParentCommentId  INT               NULL,       -- NULL = bình luận gốc, có giá trị = phản hồi
    Content          VARCHAR(2000)    NOT NULL,
    Status           VARCHAR(20)       NOT NULL DEFAULT 'Visible',
    CreatedAt        TIMESTAMP WITH TIME ZONE         NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UpdatedAt        TIMESTAMP WITH TIME ZONE         NULL,
    CONSTRAINT PK_Comments PRIMARY KEY (CommentId),
    CONSTRAINT CK_Comments_Status CHECK (Status IN ('Visible','Hidden','Deleted')),
    CONSTRAINT FK_Comments_Posts FOREIGN KEY (PostId) REFERENCES public.Posts (PostId),
    CONSTRAINT FK_Comments_Users FOREIGN KEY (UserId) REFERENCES public.Users (UserId),
    CONSTRAINT FK_Comments_Parent FOREIGN KEY (ParentCommentId) REFERENCES public.Comments (CommentId)
);

CREATE TABLE public.Reports (
    ReportId    INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    ReporterId  INT               NOT NULL,
    PostId      INT               NULL,
    CommentId   INT               NULL,
    Reason      VARCHAR(500)     NOT NULL,
    Status      VARCHAR(20)       NOT NULL DEFAULT 'Pending',
    HandledBy   INT               NULL,
    HandledAt   TIMESTAMP WITH TIME ZONE         NULL,
    CreatedAt   TIMESTAMP WITH TIME ZONE         NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_Reports PRIMARY KEY (ReportId),
    CONSTRAINT CK_Reports_Status CHECK (Status IN ('Pending','Resolved','Rejected')),
    -- Đúng một trong hai: báo cáo bài đăng HOẶC báo cáo bình luận
    CONSTRAINT CK_Reports_Target CHECK (
        (PostId IS NOT NULL AND CommentId IS NULL) OR
        (PostId IS NULL AND CommentId IS NOT NULL)),
    CONSTRAINT FK_Reports_Reporter FOREIGN KEY (ReporterId) REFERENCES public.Users (UserId),
    CONSTRAINT FK_Reports_Posts FOREIGN KEY (PostId) REFERENCES public.Posts (PostId),
    CONSTRAINT FK_Reports_Comments FOREIGN KEY (CommentId) REFERENCES public.Comments (CommentId),
    CONSTRAINT FK_Reports_HandledBy FOREIGN KEY (HandledBy) REFERENCES public.Users (UserId)
);

CREATE TABLE public.Notifications (
    NotificationId  INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    UserId          INT               NOT NULL,   -- người nhận
    ActorId         INT               NULL,       -- người gây ra hành động (NULL = hệ thống)
    Type            VARCHAR(30)       NOT NULL,
    PostId          INT               NULL,
    CommentId       INT               NULL,
    OrderId         INT               NULL,
    IsRead          BOOLEAN               NOT NULL DEFAULT FALSE,
    CreatedAt       TIMESTAMP WITH TIME ZONE         NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_Notifications PRIMARY KEY (NotificationId),
    CONSTRAINT CK_Notifications_Type CHECK (Type IN
        ('PostLike','PostComment','CommentReply','PostShare','ArtistPost','OrderDelivered')),
    -- Mỗi loại thông báo dùng đúng các cột liên kết của nó
    CONSTRAINT CK_Notifications_Links CHECK (
        (Type IN ('PostLike','PostShare','ArtistPost')
            AND PostId IS NOT NULL AND CommentId IS NULL AND OrderId IS NULL)
     OR (Type IN ('PostComment','CommentReply')
            AND PostId IS NOT NULL AND CommentId IS NOT NULL AND OrderId IS NULL)
     OR (Type = 'OrderDelivered'
            AND OrderId IS NOT NULL AND PostId IS NULL AND CommentId IS NULL)),
    CONSTRAINT FK_Notifications_User FOREIGN KEY (UserId) REFERENCES public.Users (UserId),
    CONSTRAINT FK_Notifications_Actor FOREIGN KEY (ActorId) REFERENCES public.Users (UserId),
    CONSTRAINT FK_Notifications_Posts FOREIGN KEY (PostId) REFERENCES public.Posts (PostId),
    CONSTRAINT FK_Notifications_Comments FOREIGN KEY (CommentId) REFERENCES public.Comments (CommentId),
    CONSTRAINT FK_Notifications_Orders FOREIGN KEY (OrderId) REFERENCES public.Orders (OrderId)
);

