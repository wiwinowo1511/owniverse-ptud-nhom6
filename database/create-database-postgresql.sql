    CommunityId  INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    ArtistId     INT               NOT NULL,   -- mỗi nghệ sĩ 1 cộng đồng
    Name         VARCHAR(150)     NOT NULL,
    Description  VARCHAR(1000)    NULL,
    CoverUrl     VARCHAR(500)     NULL,
    AvatarUrl    VARCHAR(500)     NULL,
    CreatedAt    TIMESTAMP WITH TIME ZONE         NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_Communities PRIMARY KEY (CommunityId),
    CONSTRAINT UQ_Communities_ArtistId UNIQUE (ArtistId),
    CONSTRAINT FK_Communities_Artists FOREIGN KEY (ArtistId) REFERENCES public.Artists (ArtistId)
);

CREATE TABLE public.CommunityMembers (
    CommunityId  INT        NOT NULL,
    UserId       INT        NOT NULL,
    JoinedAt     TIMESTAMP WITH TIME ZONE  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_CommunityMembers PRIMARY KEY (CommunityId, UserId),
    CONSTRAINT FK_CommunityMembers_Communities FOREIGN KEY (CommunityId)
        REFERENCES public.Communities (CommunityId) ON DELETE CASCADE,
    CONSTRAINT FK_CommunityMembers_Users FOREIGN KEY (UserId) REFERENCES public.Users (UserId)
);

CREATE TABLE public.Posts (
    PostId       INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CommunityId  INT               NOT NULL,
    AuthorId     INT               NOT NULL,
    Section      VARCHAR(10)       NOT NULL,   -- Artist | Fan
    Content      TEXT     NULL,       -- app kiểm tra phải có chữ hoặc media
    IsPinned     BOOLEAN               NOT NULL DEFAULT FALSE,
    PinnedAt     TIMESTAMP WITH TIME ZONE         NULL,
    Status       VARCHAR(20)       NOT NULL DEFAULT 'Visible',
    CreatedAt    TIMESTAMP WITH TIME ZONE         NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UpdatedAt    TIMESTAMP WITH TIME ZONE         NULL,
    CONSTRAINT PK_Posts PRIMARY KEY (PostId),
    CONSTRAINT CK_Posts_Section CHECK (Section IN ('Artist','Fan')),
    CONSTRAINT CK_Posts_Status CHECK (Status IN ('Visible','Hidden','Deleted')),
    CONSTRAINT FK_Posts_Communities FOREIGN KEY (CommunityId) REFERENCES public.Communities (CommunityId),
    CONSTRAINT FK_Posts_Users FOREIGN KEY (AuthorId) REFERENCES public.Users (UserId)
